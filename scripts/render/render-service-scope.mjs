import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { workspaceRoot } from '../../packages/workspace-utils/src/index.mjs';
import { allCapabilities, supportLevels } from '../../packages/core/src/azure-tier1-capabilities.mjs';

const root = workspaceRoot(import.meta.url);
const docsRoot = join(root, 'docs');
const classificationPath = join(docsRoot, 'conformance', 'azure-capture-classification.json');
const outputPath = join(docsRoot, 'SERVICE-SCOPE.md');

async function readJson(path, fallback) {
  try {
    return JSON.parse(await readFile(path, 'utf8'));
  } catch {
    return fallback;
  }
}

function implementationKind(capability) {
  if (capability.primaryModes.includes(supportLevels.OFFICIAL_EMULATOR)) return 'official-emulator-backed-local';
  if (capability.primaryModes.includes(supportLevels.GLOBALSTACK_FACADE)) return 'metadata-control-plane-facade';
  if (capability.primaryModes.includes(supportLevels.REAL_AZURE_CAPTURE_REQUIRED)) return 'capture-required';
  return 'unsupported';
}

function evidenceSummary(capability, captures) {
  const related = captures.filter(capture => capture.capabilityId === capability.id);
  const byDepth = {};
  for (const capture of related) {
    byDepth[capture.validationDepth] = (byDepth[capture.validationDepth] ?? 0) + 1;
  }
  return {
    count: related.length,
    providerValidation: byDepth['provider-validation'] ?? 0,
    armSurface: byDepth['arm-surface'] ?? 0,
    providerAccepted: byDepth['provider-accepted'] ?? 0,
    parentRouting: byDepth['provider-routing-or-parent-validation'] ?? 0,
    infrastructureGap: byDepth['capture-infrastructure-gap'] ?? 0,
  };
}

function formatEvidence(evidence) {
  return [
    `${evidence.count} total`,
    `${evidence.providerValidation} provider-validation`,
    `${evidence.armSurface} arm-surface`,
    `${evidence.providerAccepted} provider-accepted`,
    `${evidence.parentRouting} parent-routing`,
    `${evidence.infrastructureGap} infra-gap`,
  ].join('; ');
}

function cell(value) {
  if (Array.isArray(value)) return value.join('<br>');
  return String(value ?? '').replaceAll('|', '\\|');
}

function tableFor(tier, captures) {
  const rows = allCapabilities
    .filter(capability => capability.tier === tier)
    .map(capability => {
      const evidence = evidenceSummary(capability, captures);
      return [
        capability.id,
        capability.awsAnalogue,
        capability.azureEquivalent,
        capability.resourceTypes,
        implementationKind(capability),
        capability.backingEngines,
        capability.cloudValidated ? 'yes' : 'no',
        formatEvidence(evidence),
        capability.knownGaps.length,
      ];
    });

  return [
    '| Capability | AWS Analogue | Azure Equivalent | Azure Resource Types | Current Local Mode | Backing Engines | Cloud Validated | Capture Evidence | Known Gaps |',
    '|---|---|---|---|---|---|---|---|---|',
    ...rows.map(row => `| ${row.map(cell).join(' | ')} |`),
  ].join('\n');
}

const classification = await readJson(classificationPath, { captures: [] });
const captures = classification.captures ?? [];

const doc = `# Service Scope

Generated by: \`npm run docs:scope\`

This matrix is generated from \`packages/core/src/azure-tier1-capabilities.mjs\` and \`docs/conformance/azure-capture-classification.json\`.

## Reading Rules

- \`Cloud Validated = no\` means the capability must not be described as complete live Azure parity.
- \`official-emulator-backed-local\` means at least one official Microsoft emulator is part of the local strategy. It does not prove ARM control-plane or Azure failure-mode parity.
- \`metadata-control-plane-facade\` means GlobalStack accepts and stores Azure-shaped management-plane resources locally, with exact behavior limited to captured expectations.
- \`provider-accepted\` evidence is not full parity. It only means Azure accepted that request shape in the captured context.
- \`capture-infrastructure-gap\` evidence is a capture setup or subscription artifact, not service behavior.

## Tier 1

${tableFor(1, captures)}

## Tier 2

${tableFor(2, captures)}
`;

await mkdir(docsRoot, { recursive: true });
await writeFile(outputPath, doc);
console.log(`Rendered service scope to ${outputPath}`);
