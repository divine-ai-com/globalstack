async function countFiles(relativeDir) {
  const dir = join(root, relativeDir);
  const entries = await readdir(dir, { withFileTypes: true }).catch(() => []);
  let count = 0;
  for (const entry of entries) {
    const abs = join(dir, entry.name);
    if (entry.isFile()) count += 1;
    if (entry.isDirectory()) count += await countFiles(`${relativeDir}/${entry.name}`);
  }
  return count;
}

async function packageScripts() {
  const packageJson = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
  return Object.keys(packageJson.scripts).sort();
}

function artifact({ path, kind, owner, command = null, editPolicy, purpose }) {
  return { path, kind, owner, command, editPolicy, purpose };
}

function markdown(registry) {
  const lines = [
    '# Artifact Registry',
    '',
    'This registry tracks the important files and generated artifacts in the GlobalStack Azure workspace. Use it to avoid reinventing an existing layer and to preserve a product-grade repository structure.',
    '',
    'Generated by: `npm run docs:artifacts`',
    '',
    '## Operating Rules',
    '',
    '- Source files are edited directly and then validated.',
    '- Generated files are regenerated with their owner command; do not hand-edit them unless the generator is being fixed in the same change.',
    '- Real Azure evidence fixtures are immutable evidence except for explicit sanitization or classification metadata fixes.',
    '- `dist/` is generated runtime output and should not become the source of truth.',
    '- New service work must update the registry or an existing generator so future agents can find the owner path.',
    '',
    '## Summary',
    '',
    `- Registered artifacts: ${registry.artifacts.length}`,
    `- NPM commands: ${registry.commands.length}`,
    `- Azure capture fixtures: ${registry.counts.azureCaptures}`,
    `- Azure lifecycle fixtures: ${registry.counts.azureLifecycleCaptures}`,
    `- Storage data-plane fixtures: ${registry.counts.azureStorageDataPlaneCaptures}`,
    '',
  ];

  for (const group of registry.groups) {
    lines.push(`## ${group.label}`);
    lines.push('');
    lines.push('| Path | Kind | Owner | Command | Edit Policy | Purpose |');
    lines.push('|---|---|---|---|---|---|');
    for (const item of registry.artifacts.filter(entry => entry.group === group.id)) {
      lines.push(`| \`${item.path}\` | ${item.kind} | ${item.owner} | ${item.command ? `\`${item.command}\`` : ''} | ${item.editPolicy} | ${item.purpose} |`);
    }
    lines.push('');
  }

  lines.push('## Command Index');
  lines.push('');
  for (const command of registry.commands) {
    lines.push(`- \`npm run ${command}\``);
  }
  lines.push('');

  return `${lines.join('\n')}\n`;
}

